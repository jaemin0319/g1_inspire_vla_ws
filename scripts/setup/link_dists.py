#!/usr/bin/env python3
"""(Copied from so101_sim_ws/scripts/setup/link_dists.py; g1_inspire_vla_ws adds --exclude.)
Hard-link selected pip distributions from an existing (read-only) env into a new env.

Why: /mnt/isaac has ~11 GB free while a fresh `isaacsim[all,extscache]==5.1.0` install is ~18 GB.
The IGRIS env (/mnt/isaac/env) already holds byte-identical pip installs of Isaac Sim 5.1.0.0 and
torch 2.7.0 / torchvision 0.22.0. This script NEVER writes into the source env:

* the dependency closure of the requested roots is computed from the source env's metadata;
* every file listed in each distribution's RECORD is sha256-verified against RECORD;
  - hash OK and not a mutable config/runtime file -> hard link (no extra disk, same inode);
  - hash mismatch (modified after install) or mutable-looking file -> independent copy;
* RECORD entries outside site-packages (../../bin/...) are skipped; console scripts are regenerated
  for the destination interpreter;
* Isaac Sim runtime dirs (isaacsim/kit/{cache,logs,data}) are never linked; data is copied.

Usage:
  python -I link_dists.py --src /mnt/isaac/env --dst <prefix> --report out.json \
      "isaacsim[all,extscache]==5.1.0.0" torch==2.7.0 torchvision==0.22.0 ...
  python -I link_dists.py --snapshot /mnt/isaac/env --out snap.json   # content/mtime snapshot
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

from importlib.metadata import distributions

try:
    from packaging.requirements import Requirement
    from packaging.markers import default_environment
except ImportError:  # pip vendors packaging
    from pip._vendor.packaging.requirements import Requirement  # type: ignore
    from pip._vendor.packaging.markers import default_environment  # type: ignore

MUTABLE_SUFFIXES = {".json", ".toml", ".kit", ".yaml", ".yml", ".ini", ".cfg", ".config", ".xml", ".lock"}
NEVER_LINK_PREFIXES = ("isaacsim/kit/cache/", "isaacsim/kit/logs/", "isaacsim/kit/data/")
MUTABLE_MAX_BYTES = 4 * 1024 * 1024


def canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def site_packages(prefix: Path) -> Path:
    cands = sorted({p.resolve() for p in prefix.glob("lib/python3.*/site-packages")})
    if len(cands) != 1:
        raise SystemExit(f"cannot find unique site-packages in {prefix}: {cands}")
    return cands[0]


def load_dists(sp: Path):
    out = {}
    for d in distributions(path=[str(sp)]):
        out.setdefault(canon(d.metadata["Name"]), d)
    return out


def closure(dists, roots, exclude=()):
    env = default_environment()
    want = {}  # name -> set(extras)
    queue = [Requirement(r) for r in roots]
    missing = []
    while queue:
        req = queue.pop()
        n = canon(req.name)
        if n in exclude:
            continue
        if n not in dists:
            missing.append(str(req))
            continue
        d = dists[n]
        if req.specifier and not req.specifier.contains(d.version, prereleases=True):
            raise SystemExit(f"version mismatch: {req} but source has {d.version}")
        extras = set(req.extras)
        seen = want.get(n)
        if seen is not None and extras <= seen:
            continue
        want[n] = (seen or set()) | extras
        for rs in d.requires or []:
            r = Requirement(rs)
            if r.marker is None:
                queue.append(r)
                continue
            ok = r.marker.evaluate({**env, "extra": ""})
            for e in want[n]:
                ok = ok or r.marker.evaluate({**env, "extra": e})
            if ok:
                queue.append(r)
    return want, missing


def sha256_b64(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return "sha256=" + base64.urlsafe_b64encode(h.digest()).rstrip(b"=").decode()


def is_mutable(rel: str, size: int) -> bool:
    if rel.startswith(NEVER_LINK_PREFIXES):
        return True
    return Path(rel).suffix.lower() in MUTABLE_SUFFIXES and size <= MUTABLE_MAX_BYTES


SCRIPT_TMPL = """#!{python}
# generated by g1_inspire_vla_ws/scripts/setup/link_dists.py
import re, sys
from {module} import {attr_head}
if __name__ == "__main__":
    sys.argv[0] = re.sub(r"(-script\\.pyw|\\.exe)?$", "", sys.argv[0])
    sys.exit({call}())
"""


def do_link(args):
    src_sp, dst_sp = site_packages(Path(args.src)), site_packages(Path(args.dst))
    if src_sp.resolve() == dst_sp.resolve():
        raise SystemExit("src and dst are the same env")
    if os.stat(src_sp).st_dev != os.stat(dst_sp).st_dev:
        raise SystemExit("src and dst must be on the same filesystem for hard links")
    dists = load_dists(src_sp)
    excl = {canon(x) for x in (args.exclude or [])}
    want, missing = closure(dists, args.roots, excl)
    dst_existing = {canon(d.metadata["Name"]) for d in distributions(path=[str(dst_sp)])}
    report = {"src": str(src_sp), "dst": str(dst_sp), "roots": args.roots, "exclude": sorted(excl), "missing_in_src": missing,
              "skipped_already_in_dst": [], "dists": {}}
    dst_bin = Path(args.dst) / "bin"
    for n in sorted(want):
        d = dists[n]
        if n in dst_existing:
            report["skipped_already_in_dst"].append(n)
            continue
        rec = {"version": d.version, "linked": 0, "copied_mutable": 0, "copied_modified": [],
               "missing_files": [], "outside_sp": 0, "bytes_linked": 0, "bytes_copied": 0}
        for f in d.files or []:
            rel = str(f).replace("\\", "/")
            if rel.startswith("../") or "/__pycache__/" in f"/{rel}" or rel.endswith(".pyc"):
                if rel.startswith("../"):
                    rec["outside_sp"] += 1
                continue
            sp_file = src_sp / rel
            if not sp_file.is_file():
                rec["missing_files"].append(rel)
                continue
            out = dst_sp / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            if out.exists() or out.is_symlink():
                continue
            if sp_file.is_symlink():
                os.symlink(os.readlink(sp_file), out)
                continue
            size = sp_file.stat().st_size
            ok = True
            if f.hash is not None and not args.no_verify:
                ok = sha256_b64(sp_file) == f"{f.hash.mode}={f.hash.value}"
            if not ok:
                shutil.copy2(sp_file, out)
                rec["copied_modified"].append(rel)
                rec["bytes_copied"] += size
            elif is_mutable(rel, size):
                shutil.copy2(sp_file, out)
                rec["copied_mutable"] += 1
                rec["bytes_copied"] += size
            else:
                os.link(sp_file, out)
                rec["linked"] += 1
                rec["bytes_linked"] += size
        # console scripts for the destination interpreter
        scripts = []
        for ep in d.entry_points:
            if ep.group != "console_scripts":
                continue
            mod, _, attr = ep.value.partition(":")
            attr = attr.strip() or "main"
            head = attr.split(".")[0]
            target = dst_bin / ep.name
            if target.exists():
                continue
            target.write_text(SCRIPT_TMPL.format(python=Path(args.dst) / "bin" / "python",
                                                 module=mod.strip(), attr_head=head, call=attr))
            target.chmod(0o755)
            scripts.append(ep.name)
        rec["console_scripts"] = scripts
        report["dists"][n] = rec
        print(f"{n}=={d.version}: linked {rec['linked']}, copied {rec['copied_mutable']}+"
              f"{len(rec['copied_modified'])} modified, missing {len(rec['missing_files'])}", flush=True)
    tot_l = sum(r["bytes_linked"] for r in report["dists"].values())
    tot_c = sum(r["bytes_copied"] for r in report["dists"].values())
    report["total_bytes_linked"], report["total_bytes_copied"] = tot_l, tot_c
    print(f"TOTAL dists={len(report['dists'])} linked={tot_l/1e9:.2f}GB copied={tot_c/1e6:.1f}MB "
          f"missing_in_src={missing}")
    Path(args.report).write_text(json.dumps(report, indent=1))


def do_snapshot(args):
    root = Path(args.snapshot)
    h = hashlib.sha256()
    n = 0
    skip = re.compile(r"/isaacsim/kit/(cache|logs|data)/|/__pycache__/")
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for fn in sorted(filenames):
            p = os.path.join(dirpath, fn)
            if skip.search(p):
                continue
            try:
                st = os.lstat(p)
            except FileNotFoundError:
                continue
            h.update(f"{p}\0{st.st_size}\0{st.st_mtime_ns}\0{st.st_ino}\0{st.st_mode}\n".encode())
            n += 1
    out = {"root": str(root), "files": n, "digest(path,size,mtime_ns,inode,mode)": h.hexdigest()}
    Path(args.out).write_text(json.dumps(out, indent=1))
    print(json.dumps(out))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src")
    ap.add_argument("--dst")
    ap.add_argument("--report", default="link_report.json")
    ap.add_argument("--no-verify", action="store_true")
    ap.add_argument("--exclude", action="append", help="distribution names not to link and not to traverse (repeatable)")
    ap.add_argument("--snapshot", help="write a size/mtime/inode digest of this tree and exit")
    ap.add_argument("--out", default="snapshot.json")
    ap.add_argument("roots", nargs="*")
    args = ap.parse_args()
    if args.snapshot:
        do_snapshot(args)
    else:
        if not (args.src and args.dst and args.roots):
            ap.error("--src, --dst and roots are required")
        do_link(args)


if __name__ == "__main__":
    sys.exit(main())
